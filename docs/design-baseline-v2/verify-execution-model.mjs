// Design model checks only; no backend, browser launch or MCP operations.
import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const sandbox={window:{}};
for(const file of ['preview-locales.js','execution-locales.js','management-locales.js','workbench-components.js','workbench-execution.js']) vm.runInNewContext(await readFile(new URL(file,import.meta.url),'utf8'),sandbox);
const resources=sandbox.window.previewLocales;
assert.deepEqual(Object.keys(resources['zh-CN']).sort(),Object.keys(resources['en-US']).sort());
for(const values of Object.values(resources)) for(const [key,value] of Object.entries(values)) assert.ok(value.trim(),key);
const checks=['Both locales have identical, nonempty keys'];
const escape=value=>String(value).replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const ui=sandbox.window.workbenchComponents.create({escape,t:key=>resources['zh-CN'][key] || key,icon:()=>''});
const model=sandbox.window.workbenchExecution.create({ui,escape,t:key=>resources['zh-CN'][key] || key,icon:()=>'',button:(action,label,glyph,variant,extra)=>`<button data-action="${action}" ${extra || ''}>${label}</button>`,badge:value=>`<span>${value}</span>`});
const server={id:'connection-a',name:'A',url:'https://example.invalid/mcp',connected:false};
const context={projectId:'project-a',server,servers:[server],editable:true,runnable:true};
const render=()=>model.render(context);
const input=(name,value,checked=false)=>model.input({dataset:{execution:name},value,checked},context.projectId,server,context.editable);
const action=name=>model.action(name,context.projectId,server,context.editable,context.runnable);
assert.match(render(),/id="execution-backup"[^>]*data-execution="backup"\s*>/);
assert.match(render(),/未配对/);
checks.push('Fresh settings have backups off and honest unpaired state');
input('channel','browser');
assert.match(render(),/<option value="session" selected>/);
assert.doesNotMatch(render(),/<option value="local"/);
checks.push('Browser route uses session credentials without a local vault option');
input('transport','stdio');
assert.match(render(),/name="channel" value="browser"[^>]*disabled/);
assert.match(render(),/name="channel" value="agent"[^>]*checked/);
checks.push('stdio requires the local agent and disables browser execution');
input('command','');action('execution-save');assert.match(render(),/请输入启动命令/);
input('command','npx');input('args','[1]');action('execution-save');assert.match(render(),/命令参数必须/);
input('args','["-y", "example"]');action('execution-save');assert.match(render(),/已保留在本次预览/);
checks.push('Command and string-array validation preserve invalid drafts and gate save');
action('execution-pair');assert.match(render(),/模拟配对完成/);
action('execution-paired');assert.match(render(),/已配对 · 示例/);
action('execution-pair');assert.match(render(),/离线 · 示例/);
checks.push('Pairing and offline states are explicitly simulated');
assert.match(model.render({...context,server:{...server,id:'connection-b'}}),/name="transport" value="http"[^>]*checked/);
assert.match(model.render({...context,projectId:'project-b'}),/name="transport" value="http"[^>]*checked/);
checks.push('Project and connection drafts remain isolated');
context.editable=false;input('command','blocked');context.editable=true;assert.match(render(),/value="npx"/);
server.connected=true;input('command','blocked');server.connected=false;assert.match(render(),/value="npx"/);
checks.push('Viewer and connected-session settings cannot mutate');
input('command','<script>example</script>');assert.match(render(),/&lt;script&gt;/);assert.doesNotMatch(render(),/<script>/);
checks.push('User text is escaped');
await writeFile(new URL('preview-assets/execution-model-verification.json',import.meta.url),JSON.stringify({scope:'design prototype only',checks},null,2)+'\n');
console.log(`${checks.length} design model checks passed`);
