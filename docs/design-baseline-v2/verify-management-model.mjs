// Regression checks for design drafts. Does not start browsers, servers or MCP calls.
import {readFile, writeFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const sandbox={window:{}};
for(const file of ['preview-locales.js','execution-locales.js','management-locales.js','workbench-components.js','workbench-management.js']) {
  vm.runInNewContext(await readFile(new URL(file,import.meta.url),'utf8'),sandbox);
}
const resources=sandbox.window.previewLocales;
const checks=[];
assert.deepEqual(Object.keys(resources['zh-CN']).sort(),Object.keys(resources['en-US']).sort());
for(const locale of Object.values(resources)) for(const [key,value] of Object.entries(locale)) assert.ok(value.trim(),key);
checks.push('Chinese and English copy have matching nonempty keys');
let locale='zh-CN';
const t=(key,values={})=>(resources[locale][key] || key).replace(/\{\{(\w+)\}\}/g,(_,name)=>values[name] ?? name);
const escape=value=>String(value ?? '').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const helpers={escape,t,icon:()=>'',button:(action,label,glyph,variant,extra='')=>`<button data-action="${action}" ${extra}>${label}</button>`,badge:value=>`<span>${escape(value)}</span>`,field:(id,label,value,description,extra='')=>`<label for="${id}">${label}</label><input id="${id}" value="${escape(value)}" ${extra}>`,profileLabel:value=>value,roleLabel:role=>t(`common.role${role}`)};
const ui=sandbox.window.workbenchComponents.create(helpers);
const model=sandbox.window.workbenchManagement.create({...helpers,ui});
const context={projectId:'project-a',kind:'invitation',project:{id:'project-a',name:'A'},projects:[{id:'project-a',name:'A'},{id:'project-b',name:'B'}],server:{id:'server-a',name:'Server A'},profile:'开发环境',editable:true};
model.start(context.projectId,'invitation');
// A native form-shaped fixture tests identity-aware draft capture without browser APIs.
const form=(projectId,kind,controls)=>({id:'management-form',dataset:{project:projectId,kind},querySelector:selector=>controls[selector.slice(1)]});
model.capture(form('project-a','invitation',{'invite-email':{value:'designer@example.com'},'invite-project-role':{value:'Viewer'},'invite-project':{value:'project-b'}}));
assert.equal(model.get('project-a','invitation')['invite-email'],'designer@example.com');
assert.equal(model.get('project-a','invitation')['invite-project'],'project-b');
assert.match(model.render(context),/查看配置与记录，不能执行或修改/);
checks.push('Changing project access retains email and updates the access preview');
locale='en-US';
assert.match(model.render(context),/value="designer@example.com"/);
assert.match(model.render(context),/View configurations and records/);
checks.push('Language changes preserve the invitation draft and selected role');
assert.equal(model.get('project-b','invitation')['invite-email'],'');
model.capture(form('project-a','invitation',{'invite-email':{value:'A-only@example.com'}}));
assert.equal(model.get('project-b','invitation')['invite-email'],'');
checks.push('Draft capture uses the rendered form project, isolating projects');
model.clear('project-a','invitation');
model.capture(form('project-a','invitation',{'invite-email':{value:'discarded@example.com'}}));
assert.equal(model.get('project-a','invitation')['invite-email'],'');
checks.push('Cancel removes a draft; an old form cannot resurrect it');
const variable={id:'base-region',name:'REGION',value:'cn-east-1',type:'string',scope:'project',profile:'基础配置',secret:false};
model.start('project-a','variable',{variable,profile:'开发环境',serverId:'server-a'});
assert.equal(model.get('project-a','variable').profile,'基础配置');
assert.equal(model.get('project-a','variable').serverId,'server-a');
model.capture(form('project-a','variable',{'variable-type':{value:'boolean'},'variable-value':{value:'false'}}));
assert.equal(model.get('project-a','variable')['variable-value'],'false');
checks.push('Variable editing retains its original environment and connection, including false values');
const secret={...variable,id:'secret',name:'TOKEN',value:'never-render-this',secret:true,scope:'server',serverId:'server-b'};
model.start('project-a','variable',{variable:secret,profile:'开发环境',serverId:'server-a'});
const secretHtml=model.render({...context,kind:'variable'});
assert.doesNotMatch(secretHtml,/never-render-this/);
assert.match(secretHtml,/id="variable-value"[^>]*type="password"/);
assert.equal(model.get('project-a','variable').serverId,'server-b');
checks.push('Stored secret values never populate the editor; connection identity is retained');
model.setError('project-a','variable','common.theValueDoesNotMatchThe');
assert.match(model.render({...context,kind:'variable'}),/id="variable-value" aria-invalid="true" aria-describedby="dialog-error"/);
assert.match(model.render({...context,kind:'variable'}),/The value does not match/);
checks.push('Validation errors survive rendering and remain associated with the input');
assert.match(model.render({...context,editable:false}),/<fieldset class="management-fieldset" disabled>/);
assert.match(model.render({...context,editable:false}),/data-submit="create-invite" disabled/);
checks.push('Read-only pages disable both editing and submission');
model.capture(form('project-a','invitation',{'invite-email':{value:'<img src=x onerror=alert(1)>'}}));
assert.doesNotMatch(model.render(context),/<img/);
assert.match(model.render(context),/&lt;img/);
checks.push('Draft text is escaped before rendering');
await writeFile(new URL('preview-assets/management-model-verification.json',import.meta.url),JSON.stringify({scope:'design prototype only',checks},null,2)+'\n');
console.log(`${checks.length} management design model checks passed`);
